#!/bin/sh
# Барьер на файлы проекта, пока идёт команда, которая формирует команду и память:
# /beerpowers:setup, /beerpowers:onboard, /beerpowers:product-onboard. Флага нет, вне этих
# команд барьер молчит.
#
# Такая команда пишет в проект, где уже есть чужое: CLAUDE.md пользователя, его настройки,
# накопленная память. Текстом «покажи дифф, допиши в конец» это не держится — модель
# переписывает файл целиком своим вариантом, и пользователь узнаёт об этом из git. Поэтому
# на время команды:
#   Write поверх существующего файла — отказ, дописывать через Edit;
#   удаление, перенос, сброс правок и перезапись файла через Bash — отказ.
# Новые файлы, копии с шапкой generated by beerpowers, папки задач memory/tasks/ и
# .claude/.cache/ не трогаются.
#
# Окно команды. Хук слушает три события и различает их по hook_event_name:
#   UserPromptSubmit — промпт начинается с одной из трёх команд: окно открыто; с любой другой
#                      слеш-команды: окно закрыто. Обычный текст окно не меняет — диалог
#                      команды идёт и такими сообщениями;
#   PreToolUse Skill — модель вызвала одну из трёх команд сама: окно открыто;
#   PreToolUse Write|Bash — проверка, если окно открыто.
# Окно — файл .claude/.cache/user-files-window/<session_id>; живёт до закрытия, но не
# дольше шести часов. Команда закрывает его последним шагом:
#   sh "<корень плагина>/hooks/guard-user-files.sh" --close

lib="$(dirname -- "$0")/lib/guard.sh"
[ -f "$lib" ] || exit 0
. "$lib"

WIN_DIR="$GUARD_ROOT/.claude/.cache/user-files-window"

if [ "$1" = "--close" ]; then
  [ -d "$WIN_DIR" ] && find "$WIN_DIR" -type f -exec rm -f {} + 2>/dev/null
  echo "окно барьера на файлы закрыто"
  exit 0
fi

input=$(cat)
# Ранний отсев: окно открывают только промпт и вызов Skill, остальным событиям без открытого
# окна разбирать нечего. Проверка — glob оболочки, без запуска процессов: барьер срабатывает
# на каждой команде Bash и каждой записи файла.
case "$input" in
  *UserPromptSubmit*|*Skill*) ;;
  *) set -- "$WIN_DIR"/*; [ -e "$1" ] || exit 0 ;;
esac
event=$(guard_json "$input" '.hook_event_name' hook_event_name)
session=$(guard_json "$input" '.session_id' session_id)
case "$session" in ''|*[!A-Za-z0-9_.-]*) exit 0 ;; esac
marker="$WIN_DIR/$session"

window_cmd() {
  case "$1" in
    setup|onboard|product-onboard) return 0 ;;
  esac
  return 1
}

open_window() {
  mkdir -p "$WIN_DIR" 2>/dev/null || return 0
  printf '%s\n' "$1" > "$marker" 2>/dev/null
}

if [ "$event" = "UserPromptSubmit" ]; then
  prompt=$(guard_json "$input" '.prompt' prompt)
  prompt=${prompt#"${prompt%%[! ]*}"}
  case "$prompt" in
    /beerpowers:*)
      name=${prompt#/beerpowers:}
      name=${name%%[ 	]*}
      if window_cmd "$name"; then open_window "$name"; else rm -f "$marker" 2>/dev/null; fi
      ;;
    /*) rm -f "$marker" 2>/dev/null ;;
  esac
  exit 0
fi

tool=$(guard_json "$input" '.tool_name' tool_name)

if [ "$tool" = "Skill" ]; then
  skill=$(guard_json "$input" '.tool_input.skill' skill)
  skill=${skill#/}
  skill=${skill#beerpowers:}
  window_cmd "$skill" && open_window "$skill"
  exit 0
fi

[ -f "$marker" ] || exit 0
[ -n "$(find "$marker" -mmin -360 2>/dev/null)" ] || { rm -f "$marker" 2>/dev/null; exit 0; }
active=$(head -n 1 "$marker" 2>/dev/null)

# Путь вне защиты: папки задач, кеш хуков, копии плагина с шапкой.
exempt() {
  p=$(printf '%s' "$1" | tr '\\' '/' | tr -s '/')
  case "$p" in
    memory/tasks/*|*/memory/tasks/*|.claude/.cache/*|*/.claude/.cache/*) return 0 ;;
  esac
  [ -f "$1" ] && head -n 3 "$1" 2>/dev/null | grep -q 'generated by beerpowers' && return 0
  return 1
}

if [ "$tool" = "Write" ]; then
  file=$(guard_file_path "$input")
  [ -z "$file" ] && exit 0
  file=$(printf '%s' "$file" | tr '\\' '/' | tr -s '/')
  case "$file" in
    /*|[A-Za-z]:/*) path=$file ;;
    *) path="$GUARD_ROOT/$file" ;;
  esac
  [ -e "$path" ] || exit 0
  exempt "$path" && exit 0
  guard_deny "Файл ${file##*/} уже существует, а идёт /beerpowers:$active: эта команда не заменяет существующие файлы целиком — в них может быть то, что писал человек. Дописывай через Edit и покажи человеку дифф. Нужна замена целиком — скажи об этом человеку: файл заменит или удалит он сам."
fi

[ "$tool" = "Bash" ] || exit 0
cmd=$(guard_command "$input")
[ -z "$cmd" ] && exit 0

# Данные — не команды: тело heredoc и содержимое кавычек не разбираются.
cmd=${cmd%%<<*}
cmd=$(printf '%s' "$cmd" | sed 's/\\"[^\\]*\\"//g; s/"[^"]*"//g; s/'"'"'[^'"'"']*'"'"'//g')

deny_bash() {
  guard_deny "Идёт /beerpowers:$active: $1 Команда, которая формирует команду и память, файлы проекта не удаляет, не переносит и не перезаписывает. Нужно — назови человеку файл и причину, он сделает сам."
}

exists_in_project() {
  case "$1" in
    ''|/dev/null|NUL|nul|'&'*) return 1 ;;
  esac
  ( cd "$GUARD_ROOT" 2>/dev/null && [ -f "$1" ] ) || return 1
  exempt "$GUARD_ROOT/$1" && return 1
  return 0
}

check_segment() {
  set -f
  # shellcheck disable=SC2086
  set -- $1
  set +f
  while [ $# -gt 0 ]; do
    case "$1" in
      *=*) shift ;;
      *) break ;;
    esac
  done
  [ $# -gt 0 ] || return 0
  name=$1
  case "$name" in
    rm|rmdir|unlink|del|erase|rd|Remove-Item|remove-item|ri|*/rm|*/unlink)
      deny_bash "удаление ($name) запрещено." ;;
    mv|move|Move-Item|move-item|*/mv)
      deny_bash "перенос ($name) запрещён — он заменяет файл назначения и убирает исходный." ;;
    cp|copy|Copy-Item|copy-item|*/cp)
      for last in "$@"; do :; done
      exists_in_project "$last" && deny_bash "копирование поверх существующего $last запрещено."
      ;;
    git|*/git)
      shift
      while [ $# -gt 0 ]; do
        case "$1" in
          -C|-c) shift 2 ;;
          -*) shift ;;
          *) break ;;
        esac
      done
      sub=$1
      [ $# -gt 0 ] && shift
      case "$sub" in
        rm|mv|clean|restore) deny_bash "git $sub запрещён." ;;
        reset) case " $* " in *" --hard "*) deny_bash "git reset --hard запрещён — он сбрасывает правки человека." ;; esac ;;
        checkout) case " $* " in *" -- "*|*" . "*) deny_bash "git checkout с путями запрещён — он сбрасывает правки человека." ;; esac ;;
      esac
      ;;
  esac
  return 0
}

old_ifs=$IFS
IFS='
'
for segment in $(printf '%s' "$cmd" | tr ';&|' '\n\n\n'); do
  IFS=$old_ifs
  # Перезапись перенаправлением: «> файл» поверх существующего; «>>» дописывает и проходит.
  rest=$segment
  while :; do
    case "$rest" in
      *'>'*) ;;
      *) break ;;
    esac
    before=${rest%%'>'*}
    rest=${rest#*'>'}
    case "$rest" in
      '>'*) rest=${rest#'>'}; continue ;;
    esac
    case "$before" in
      *[0-9]) case "$rest" in '&'*) continue ;; esac ;;
    esac
    target=${rest#"${rest%%[! ]*}"}
    target=${target%%[ 	]*}
    exists_in_project "$target" && deny_bash "перезапись $target перенаправлением > запрещена; дописать в конец — >>, правка — Edit."
  done
  check_segment "$segment"
  IFS='
'
done
IFS=$old_ifs

exit 0
