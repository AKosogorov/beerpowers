#!/bin/sh
# PreToolUse hook (Bash): не даёт закоммитить новые комментарии, не показав их глазами.
# Флаг barriers.guard-comments в .claude/workspace.json, по умолчанию включён.
#
# Правило требует перед сдачей перечитать добавленные строки комментариев в диффе и удалить
# пересказ кода. Правило текстом не работает: комментарий в момент написания ощущается как
# добросовестность, и перечитывание пропускается — мусор ловит ревьюер или пользователь,
# а не автор.
#
# Машинно отличить нужный комментарий от пересказа нельзя, поэтому хук не оценивает
# содержание, кроме одного признака: ссылки на контекст задачи (метка charter с номером,
# «ответ N», memory/tasks/) — папка задачи после мержа удаляется, и такой комментарий
# не расшифровать. Голый код задачи не считается: его находят в git. Такие строки хук называет
# отдельно. Он печатает добавленные комментарии и блокирует коммит ровно один раз:
# повторный коммит того же индекса проходит. Цена — один лишний шаг, смысл — комментарии
# гарантированно попадают на глаза до того, как уедут в историю.
#
# Каталоги comments.excludeDirs своего репозитория исключены: генерируемый код приносит
# комментарии десятками при каждой регенерации, руками он не правится, и показ его строк
# только топит настоящие. По той же причине исключены копии плагина в .claude/ — файлы
# с шапкой `generated by beerpowers`: их целиком перезаписывает /beerpowers:update.

lib="$(dirname -- "$0")/lib/guard.sh"
[ -f "$lib" ] || exit 0
. "$lib"

input=$(cat)
# Ранний отсев по сырому событию — до чтения флага и разбора JSON: барьер срабатывает
# на каждой команде Bash, а каждый запуск sed на Windows стоит десятки миллисекунд.
case "$input" in
  *commit*) ;;
  *) exit 0 ;;
esac

guard_gate guard-comments on

STATE_DIR="$GUARD_ROOT/.claude/.cache"
STATE_FILE="$STATE_DIR/comment-guard"

cmd=$(guard_command "$input")

[ -z "$cmd" ] && exit 0

# Данные — не команды: тело сообщения коммита может упоминать любые формы git.
naked=$(guard_strip_data "$cmd")
guard_git_sub "$naked" commit || exit 0

# Каталог репозитория: из флага -C, иначе текущий. Путь в -C может быть переменной
# (`git -C $R …`): хук видит текст до раскрытия, каталога с таким именем нет, и git молча
# вернул бы пусто — тогда проверяется корень проекта.
repo=$(printf '%s' "$naked" | sed -n 's/.*git[[:space:]]\{1,\}-C[[:space:]]\{1,\}\([^[:space:]]*\).*/\1/p' | head -n 1)
[ -z "$repo" ] && repo="."
[ -d "$repo" ] || repo="$GUARD_ROOT"

# `commit -a` / `--all` забирает и неиндексированные правки отслеживаемых файлов: их комментарии
# видны только в диффе от HEAD.
range=--cached
if printf '%s' "$naked" | grep -Eq 'commit([[:space:]].*)?[[:space:]](-[A-Za-z]*a[A-Za-z]*|--all)([[:space:]]|$)'; then
  range=HEAD
fi

# Исключения записаны путём от корня workspace — projects/<репо>/<путь> — и действуют только
# в своём репозитории: один и тот же каталог генерируемый в одном и рукописный в другом.
# Репозиторий узнаётся по имени каталога: рабочее дерево задачи названо так же, как репозиторий
# (worktrees/<КОД>/<репо>), поэтому запись покрывает и его.
repo_name=$(cd -- "$repo" 2>/dev/null && pwd)
repo_name=${repo_name##*/}
set --
for dir in $(guard_ws_list excludeDirs); do
  dir=${dir%/}
  case "$dir" in
    "projects/$repo_name/"?*) set -- "$@" ":(exclude)${dir#"projects/$repo_name/"}/*" ;;
  esac
done

# Разбор диффа — одним git diff и одним awk: на Windows запуск каждого процесса под нагрузкой
# стоит сотни миллисекунд, и прежняя цепочка из трёх десятков процессов упиралась в таймаут хука.
#
# Набор файла — по расширению: `//`-языки, `#`-языки, PHP — оба. Копия плагина узнаётся
# по шапке, а не по каталогу: рядом с копиями в .claude/bin/ лежат проектные скрипты без шапки
# (worktree-setup, testdb-ensure), и их комментарии писал автор коммита.
#
# Комментарий в начале строки и в конце строки после кода. Перед хвостовым `//` и `#` нужен
# пробел: так `https://` и `${#var}` комментарием не считаются. `#!` — shebang, `#[` — атрибут
# PHP: не комментарии. Добавленная строка, которая сама начинается с `++`, выглядит в диффе как
# заголовок `+++` и пропускается. К заголовку файла с пробелом в имени git дописывает табуляцию.
#
# Вывод — строки `//`-набора с префиксом s, затем `#`-набора с префиксом h; пусто — показывать
# нечего. Регулярки идут через окружение: awk -v разобрал бы их обратные косые.
found=$(git -c core.quotePath=false -C "$repo" diff $range -U0 --no-color --no-ext-diff -- \
  '*.ts' '*.tsx' '*.js' '*.jsx' '*.mjs' '*.cjs' '*.vue' '*.svelte' '*.php' \
  '*.css' '*.scss' '*.less' '*.go' '*.java' '*.kt' '*.kts' '*.swift' '*.rs' \
  '*.c' '*.h' '*.cc' '*.cpp' '*.hpp' '*.cs' '*.scala' '*.dart' '*.html' \
  '*.py' '*.sh' '*.bash' '*.rb' '*.pl' '*.yml' '*.yaml' '*.toml' \
  '*.ex' '*.exs' '*Dockerfile' "$@" 2>/dev/null \
  | REPO=$repo \
    SLASH_RE='^[+][[:space:]]*(//|/[*]|[*][^/]|<!--|[{][{]--)|^[+].*[^[:space:]][[:space:]]+(//|/[*])|<!--|[{][{]--' \
    HASH_RE='^[+][[:space:]]*#([^![]|$)|^[+].*[^[:space:]][[:space:]]+#[[:space:]]' \
    awk '
    BEGIN { repo = ENVIRON["REPO"]; sre = ENVIRON["SLASH_RE"]; hre = ENVIRON["HASH_RE"] }
    /^diff --git / { head = 1; kind = ""; next }
    head && /^\+\+\+ / {
      f = substr($0, 5); sub(/\t$/, "", f); sub(/^"/, "", f); sub(/"$/, "", f); sub(/^b\//, "", f)
      if (f ~ /\.(ts|tsx|js|jsx|mjs|cjs|vue|svelte|php|css|scss|less|go|java|kt|kts|swift|rs|c|h|cc|cpp|hpp|cs|scala|dart|html)$/) kind = kind "s"
      if (f ~ /(\.(py|sh|bash|rb|pl|yml|yaml|toml|php|ex|exs)|Dockerfile)$/) kind = kind "h"
      if (index(f, ".claude/") == 1) {
        path = repo "/" f
        for (i = 0; i < 3 && (getline line < path) > 0; i++) if (index(line, "generated by beerpowers v")) kind = ""
        close(path)
      }
      next
    }
    /^@@/ { head = 0; next }
    head || /^\+\+\+/ || !/^\+/ { next }
    { if (kind ~ /s/ && $0 ~ sre) s[++ns] = $0; if (kind ~ /h/ && $0 ~ hre) h[++nh] = $0 }
    END { for (i = 1; i <= ns; i++) print "s" s[i]; for (i = 1; i <= nh; i++) print "h" h[i] }')

[ -z "$found" ] && exit 0

slash=$(printf '%s\n' "$found" | sed -n 's/^s//p')
hash=$(printf '%s\n' "$found" | sed -n 's/^h//p')
added=$(printf '%s\n%s\n' "$slash" "$hash" | grep -v '^$')

# Тот же набор комментариев уже показывали — пропускаем, иначе коммит не сделать никогда.
fingerprint=$(printf '%s' "$added" | git hash-object --stdin 2>/dev/null)
if [ -n "$fingerprint" ] && [ -f "$STATE_FILE" ] && [ "$(cat "$STATE_FILE")" = "$fingerprint" ]; then
  exit 0
fi

mkdir -p "$STATE_DIR" 2>/dev/null
[ -n "$fingerprint" ] && printf '%s' "$fingerprint" > "$STATE_FILE"

# Строки, у которых в тексте комментария — не в коде перед ним — есть ссылка на контекст задачи.
# Границы слова — классами: \b есть не в каждом awk. Регулярка идёт через окружение: awk -v
# разобрал бы её обратные косые.
task_context() { # task_context <регулярка начала комментария>
  START=$1 awk '
    BEGIN { start = ENVIRON["START"] }
    match($0, start) {
      c = substr($0, RSTART)
      if (c ~ /(^|[^[:alnum:]_])[QCBRNSM][0-9]+($|[^[:alnum:]_])/ || c ~ /(О|о)твет[[:space:]]+[0-9]+/ || index(c, "memory/tasks/")) print
    }'
}
context=$(
  printf '%s\n' "$slash" | task_context '^\+[[:space:]]*(//|/\*|\*|<!--|\{\{--)|[[:space:]](//|/\*)|<!--|\{\{--'
  printf '%s\n' "$hash" | task_context '^\+[[:space:]]*#|[[:space:]]#'
)

json_lines() { sed 's/^+//; s/^[[:space:]]*//; s/\\/\\\\/g; s/"/\\"/g' | tr '\n' '|' | sed 's/|/\\n  /g'; }

context_note=""
if [ -n "$context" ]; then
  context_note="Ссылаются на контекст задачи — метка charter с номером, «ответ N», memory/tasks/; после мержа папка задачи удаляется, и их не расшифровать. Напиши причину словами или удали; имя вроде S3 или R2 оставь.\\n\\n  $(printf '%s\n' "$context" | head -n 10 | json_lines)\\n"
fi

count=$(printf '%s\n' "$added" | wc -l | tr -d ' ')
shown=$(printf '%s\n' "$added" | head -n 30 | json_lines)

printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Новых строк комментариев в индексе: %s. Перечитай их и удали те, что пересказывают строку под собой или защищают ожидаемое поведение; оставь только неочевидное «почему» — скрытое ограничение, обходной путь, неожиданное поведение стороннего кода.\\n\\n  %s\\n%sПовтори ту же команду коммита, когда решишь по каждому: тот же набор строк второй раз не блокируется."}}\n' "$count" "$shown" "$context_note"
exit 0
