#!/bin/sh
# PreToolUse hook (AskUserQuestion): не даёт вынести артефакт на утверждение без ссылки на файл.
# Флаг barriers.guard-approval-link в .claude/workspace.json, по умолчанию включён.
#
# Норма — .claude/team-lead.md, «Развилки с пользователем»: вопрос об утверждении брифа, ADR,
# плана или черновика идёт вместе со ссылкой на файл. Правило о ссылках в ответе человеку
# не срабатывало: текст вопроса AskUserQuestion не воспринимается как ответ человеку,
# и человек получал «Утверждаешь бриф?» с пересказом, но без файла.
#
# Хук видит только вход вопроса, а не текст ответа над ним, поэтому проверяет путь в самом
# вопросе: слова утверждения есть, пути к файлу задачи, ADR или .md нет — отказ. Слова
# ловят и вопросы не об утверждении, поэтому отказ — ровно один раз: повтор того же вызова
# проходит.

lib="$(dirname -- "$0")/lib/guard.sh"
[ -f "$lib" ] || exit 0
. "$lib"

input=$(cat)
# Только поля вопроса: путь транскрипта и рабочий каталог стоят в событии раньше tool_input
# и могли бы сойти за путь к артефакту.
asked=${input#*\"tool_input\"}
[ "$asked" = "$input" ] && exit 0

printf '%s' "$asked" | grep -Eq 'утвержд|Утвержд|УТВЕРЖД|бриф|Бриф|черновик|Черновик|план|План|[Aa]pprov|[Bb]rief|ADR' || exit 0

guard_gate guard-approval-link on

# Путь с прямыми или экранированными обратными слэшами: memory/tasks/…, memory/adr/…, *.md.
printf '%s' "$asked" | grep -Eq 'memory(/|\\\\)+(tasks|adr)(/|\\\\)|\.md([^A-Za-z0-9]|$)' && exit 0

STATE_DIR="$GUARD_ROOT/.claude/.cache"
STATE_FILE="$STATE_DIR/approval-link-guard"

# Тот же вопрос уже отклоняли — пропускаем, иначе ложное срабатывание не обойти.
sum=$(printf '%s' "$asked" | cksum | tr -d ' ')
if [ -f "$STATE_FILE" ] && [ "$(cat "$STATE_FILE")" = "$sum" ]; then
  rm -f "$STATE_FILE"
  exit 0
fi
mkdir -p "$STATE_DIR" 2>/dev/null
printf '%s' "$sum" > "$STATE_FILE"

guard_deny 'Вопрос похож на утверждение артефакта, а пути к файлу в нём нет: дай ссылку на артефакт и SendUserFile до вопроса. В том же сообщении, перед вопросом, — кликабельная markdown-ссылка на файл и карточка SendUserFile (display: render); путь к файлу — и в тексте вопроса (.claude/team-lead.md, «Развилки с пользователем»). Вопрос не об утверждении — повтори тот же вызов: второй раз он проходит.'
