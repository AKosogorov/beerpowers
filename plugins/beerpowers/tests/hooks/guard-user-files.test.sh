#!/bin/sh
# Фикстуры hooks/guard-user-files.sh: окно открывается командой, затем проверяются записи.
# Ожидание — решение хука: deny (в выводе permissionDecision deny) или pass (пустой вывод).
# Печатает pass/fail, код выхода ненулевой, если упал хоть один случай.
#
# Запуск: sh plugins/beerpowers/tests/hooks/guard-user-files.test.sh

here=$(cd -- "$(dirname -- "$0")" && pwd)
hook_sh="$here/../../hooks/guard-user-files.sh"
tmp=$(mktemp -d 2>/dev/null) || tmp="${TMPDIR:-/tmp}/bp-user-files-$$"
mkdir -p "$tmp" || exit 2
trap 'rm -rf "$tmp"' EXIT

failed=0
total=0

project() {
  rm -rf "$tmp/p"
  mkdir -p "$tmp/p/.claude/bin" "$tmp/p/memory/project" "$tmp/p/memory/tasks/T-1"
  printf '# Проект\n\nправила человека\n' > "$tmp/p/CLAUDE.md"
  printf 'карта\n' > "$tmp/p/memory/project/project-map.md"
  printf 'отчёт\n' > "$tmp/p/memory/tasks/T-1/review-report.md"
  printf '#!/bin/sh\n# generated by beerpowers v2.0.0 — не править\n' > "$tmp/p/.claude/bin/tasks-status"
}

send() {
  printf '%s' "$1" | CLAUDE_PROJECT_DIR="$tmp/p" sh "$hook_sh" > "$tmp/out" 2>/dev/null
}

prompt() { send "{\"hook_event_name\":\"UserPromptSubmit\",\"session_id\":\"s1\",\"prompt\":\"$1\"}"; }
skill() { send "{\"hook_event_name\":\"PreToolUse\",\"session_id\":\"s1\",\"tool_name\":\"Skill\",\"tool_input\":{\"skill\":\"$1\"}}"; }
write() { send "{\"hook_event_name\":\"PreToolUse\",\"session_id\":\"s1\",\"tool_name\":\"Write\",\"tool_input\":{\"file_path\":\"$1\",\"content\":\"x\"}}"; }
bash_() { send "{\"hook_event_name\":\"PreToolUse\",\"session_id\":\"s1\",\"tool_name\":\"Bash\",\"tool_input\":{\"command\":\"$1\"}}"; }

expect() {
  total=$((total + 1))
  if grep -q '"permissionDecision":"deny"' "$tmp/out"; then got=deny; else got=pass; fi
  if [ "$got" = "$2" ]; then echo "pass  $1"; else echo "FAIL  $1 (ждали $2, получили $got)"; failed=$((failed + 1)); fi
}

project
write "$tmp/p/CLAUDE.md"; expect "вне команды Write поверх CLAUDE.md — молчит" pass
bash_ "rm CLAUDE.md"; expect "вне команды rm — молчит" pass

project; prompt "/beerpowers:setup shop"
write "$tmp/p/CLAUDE.md"; expect "setup: Write поверх существующего CLAUDE.md — отказ" deny
write "$tmp/p/memory/project/project-map.md"; expect "setup: Write поверх памяти — отказ" deny
write "memory/project/project-map.md"; expect "setup: относительный путь — отказ" deny
write "$tmp/p/memory/project/glossary.md"; expect "setup: новый файл — проходит" pass
write "$tmp/p/memory/tasks/T-1/review-report.md"; expect "setup: папка задачи — проходит" pass
write "$tmp/p/.claude/bin/tasks-status"; expect "setup: копия с шапкой generated by — проходит" pass
bash_ "rm CLAUDE.md"; expect "setup: rm — отказ" deny
bash_ "git -C . rm --cached CLAUDE.md"; expect "setup: git rm — отказ" deny
bash_ "mv CLAUDE.md CLAUDE.old"; expect "setup: mv — отказ" deny
bash_ "echo x > CLAUDE.md"; expect "setup: > поверх существующего — отказ" deny
bash_ "echo x >> CLAUDE.md"; expect "setup: >> дописывает — проходит" pass
bash_ "echo x > memory/project/new.md"; expect "setup: > в новый файл — проходит" pass
bash_ "git status 2>/dev/null"; expect "setup: 2>/dev/null — проходит" pass
bash_ "git checkout -- CLAUDE.md"; expect "setup: git checkout -- путь — отказ" deny
bash_ "git log --oneline -5"; expect "setup: чтение git — проходит" pass
bash_ "git commit -m \\\"rm CLAUDE.md\\\""; expect "setup: rm в кавычках — данные, проходит" pass

prompt "ещё поправь состав"
write "$tmp/p/CLAUDE.md"; expect "обычное сообщение окно не закрывает" deny

prompt "/beerpowers:doctor"
write "$tmp/p/CLAUDE.md"; expect "другая команда плагина окно закрывает" pass

project; prompt "/beerpowers:onboard"
write "$tmp/p/memory/project/project-map.md"; expect "onboard: Write поверх памяти — отказ" deny
CLAUDE_PROJECT_DIR="$tmp/p" sh "$hook_sh" --close >/dev/null
write "$tmp/p/memory/project/project-map.md"; expect "после --close — проходит" pass

project; skill "beerpowers:product-onboard"
write "$tmp/p/memory/project/project-map.md"; expect "вызов через Skill открывает окно" deny

project; skill "beerpowers:page-screenshot"
write "$tmp/p/CLAUDE.md"; expect "другой скилл окно не открывает" pass

project; prompt "/compact"; prompt "/beerpowers:setup"; prompt "/compact"
write "$tmp/p/CLAUDE.md"; expect "чужая слеш-команда окно закрывает" pass

echo
echo "$total случаев, упало $failed"
[ "$failed" -eq 0 ]
